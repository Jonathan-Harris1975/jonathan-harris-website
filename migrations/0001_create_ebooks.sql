CREATE TABLE IF NOT EXISTS ebooks (
 ebook_id INTEGER PRIMARY KEY,
 slug TEXT NOT NULL UNIQUE,
 title TEXT NOT NULL,
 short_description TEXT NOT NULL DEFAULT '',
 description TEXT NOT NULL DEFAULT '',
 summary TEXT NOT NULL DEFAULT '',
 topic TEXT NOT NULL DEFAULT '',
 tags_json TEXT NOT NULL DEFAULT '[]' CHECK (json_valid(tags_json)),
 keywords_json TEXT NOT NULL DEFAULT '[]' CHECK (json_valid(keywords_json)),
 audience TEXT NOT NULL DEFAULT '',
 who_for TEXT NOT NULL DEFAULT '',
 what_book_covers TEXT NOT NULL DEFAULT '',
 what_youll_learn_json TEXT NOT NULL DEFAULT '[]' CHECK (json_valid(what_youll_learn_json)),
 why_it_matters TEXT NOT NULL DEFAULT '',
 tone TEXT NOT NULL DEFAULT '',
 author TEXT NOT NULL DEFAULT '',
 identifier TEXT NOT NULL DEFAULT '',
 manuscript_filename TEXT NOT NULL DEFAULT '',
 manuscript_r2_key TEXT NOT NULL UNIQUE,
 manuscript_url TEXT DEFAULT NULL,
 manuscript_title_observed TEXT NOT NULL DEFAULT '',
 title_alignment_status TEXT NOT NULL DEFAULT '',
 asin TEXT NOT NULL DEFAULT '',
 page_count INTEGER,
 publication_date TEXT,
 book_url TEXT NOT NULL DEFAULT '',
 buy_now_url TEXT NOT NULL DEFAULT '',
 redirect_url TEXT NOT NULL DEFAULT '',
 cover_art_url TEXT NOT NULL DEFAULT '',
 legacy_alias_url TEXT NOT NULL DEFAULT '',
 manuscript_format TEXT NOT NULL DEFAULT 'PDF' CHECK (manuscript_format = 'PDF'),
 content_type TEXT NOT NULL DEFAULT 'application/pdf' CHECK (content_type = 'application/pdf'),
 storage_bucket TEXT NOT NULL DEFAULT 'kdp' CHECK (storage_bucket = 'kdp'),
 created_at TEXT NOT NULL DEFAULT (datetime('now')),
 updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS idx_ebooks_topic ON ebooks(topic);
CREATE INDEX IF NOT EXISTS idx_ebooks_identifier ON ebooks(identifier);
